// Store-only ZIP writer. Local CRC32 keeps this dependency-free and type-safe.

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(data: Buffer): number {
  let c = 0xffffffff;
  for (let i = 0; i < data.length; i++) {
    c = CRC_TABLE[(c ^ data[i]) & 0xff] ^ (c >>> 8);
  }
  return (c ^ 0xffffffff) >>> 0;
}

export type ZipPhoto = {
  id: string;
  fileName: string;
  uploaderName: string;
  createdAt: Date;
};

function dosDateTime(date: Date): { time: number; date: number } {
  return {
    time: (date.getUTCHours() << 11) | (date.getUTCMinutes() << 5) | (date.getUTCSeconds() >> 1),
    date: ((date.getUTCFullYear() - 1980) << 9) | ((date.getUTCMonth() + 1) << 5) | date.getUTCDate(),
  };
}

function slug(value: string): string {
  return (
    value
      .normalize("NFKD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
      .slice(0, 40) || "guest"
  );
}

export function photoEntryName(photo: ZipPhoto): string {
  const day = photo.createdAt.toISOString().slice(0, 10);
  return `${day}-${slug(photo.uploaderName)}-${photo.id.slice(0, 8)}.jpg`;
}

/**
 * Streams a store-only ZIP (JPEGs do not compress). Full-size files only.
 * shortcut: ZIP32 store-only; upgrade to ZIP64 if an archive can exceed
 * 4 GB or 65,535 entries. The route pre-checks both limits.
 */
export async function* zipPhotoChunks(
  photos: readonly ZipPhoto[],
  readFile: (fileName: string) => Promise<Buffer | null>
): AsyncGenerator<Buffer> {
  const central: Buffer[] = [];
  let offset = 0;

  for (const photo of photos) {
    const data = await readFile(photo.fileName);
    if (!data) continue;

    const name = Buffer.from(photoEntryName(photo), "utf8");
    const { time, date } = dosDateTime(photo.createdAt);
    const checksum = crc32(data);

    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0, 6);
    local.writeUInt16LE(0, 8);
    local.writeUInt16LE(time, 10);
    local.writeUInt16LE(date, 12);
    local.writeUInt32LE(checksum, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);

    const localOffset = offset;
    const localHeader = Buffer.concat([local, name]);
    yield localHeader;
    offset += localHeader.length;
    yield data;
    offset += data.length;

    const cd = Buffer.alloc(46);
    cd.writeUInt32LE(0x02014b50, 0);
    cd.writeUInt16LE(20, 4);
    cd.writeUInt16LE(20, 6);
    cd.writeUInt16LE(0, 8);
    cd.writeUInt16LE(0, 10);
    cd.writeUInt16LE(time, 12);
    cd.writeUInt16LE(date, 14);
    cd.writeUInt32LE(checksum, 16);
    cd.writeUInt32LE(data.length, 20);
    cd.writeUInt32LE(data.length, 24);
    cd.writeUInt16LE(name.length, 28);
    cd.writeUInt16LE(0, 30);
    cd.writeUInt16LE(0, 32);
    cd.writeUInt16LE(0, 34);
    cd.writeUInt16LE(0, 36);
    cd.writeUInt32LE(0, 38);
    cd.writeUInt32LE(localOffset, 42);
    central.push(Buffer.concat([cd, name]));
  }

  const centralOffset = offset;
  let centralSize = 0;
  for (const entry of central) {
    yield entry;
    centralSize += entry.length;
  }

  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0);
  eocd.writeUInt16LE(0, 4);
  eocd.writeUInt16LE(0, 6);
  eocd.writeUInt16LE(central.length, 8);
  eocd.writeUInt16LE(central.length, 10);
  eocd.writeUInt32LE(centralSize, 12);
  eocd.writeUInt32LE(centralOffset, 16);
  eocd.writeUInt16LE(0, 20);
  yield eocd;
}
